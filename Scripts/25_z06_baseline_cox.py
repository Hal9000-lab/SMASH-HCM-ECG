#!/usr/bin/env python3
"""
Step 25 -- Baseline z06 and future clinical events (Cox proportional hazards).

Purpose
-------
Test whether baseline HCM-oriented lateral/frontal QRS-force coordinate H_z_06
is associated with subsequent incident clinical events.

Design
------
- exact ECG-to-SHaRe mappings already defined in Step 24a
- landmark = first valid ECG with finite H_z_06
- exclude endpoint events prevalent/on the landmark date, positive events with
  unavailable timing, events after recorded censoring, and subjects with no
  positive follow-up after the landmark
- exposure = baseline H_z_06 standardized to 1 SD using the full 623-subject
  exact-mapped baseline-z06 cohort (same scaling for all endpoints)
- Model 1: z06 only
- Model 2: z06 + baseline age + sex
- primary candidate endpoints: Composite_HF, Atrial_Fibrillation,
  Unplanned_CV_Hospitalization, Composite_Overall
- Composite_VArrhythmia is reported as exploratory because of sparse events
- Breslow handling of tied event times
- BH FDR applied to the z06 tests across the 4 primary candidate endpoints,
  separately for unadjusted and age/sex-adjusted models

This script consumes the auditable subject-level Step-24 table. It does not
retrain any latent model and never uses ECGs obtained after baseline to define
baseline z06.

Canonical inputs
----------------
Results/24_Z06_EventRiskFeasibility/z06_event_feasibility_subject_level.csv
Data/SHaReData-FLO.xlsx

Canonical outputs
-----------------
Results/25_Z06_BaselineCox/
"""
from __future__ import annotations

import math
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path
import re

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, median_abs_deviation
from statsmodels.duration.hazard_regression import PHReg
from statsmodels.stats.multitest import multipletests

def infer_project_root() -> Path:
    """Locate the SMASH-HCM project root from the script location or cwd."""
    candidates = []
    try:
        here = Path(__file__).resolve()
        candidates.extend([here.parent, *here.parents])
    except NameError:
        pass

    cwd = Path.cwd().resolve()
    candidates.extend([cwd, *cwd.parents])

    seen = set()
    for p in candidates:
        if p in seen:
            continue
        seen.add(p)
        if (p / "Scripts").exists() and (p / "Results").exists():
            return p

    raise RuntimeError(
        "Cannot locate SMASH-HCM project root (expected Scripts/ and Results/)."
    )


ROOT = infer_project_root()
DATA = ROOT / "Data"
RESULTS = ROOT / "Results"

# Existing Step-24 output. Step 24 does not need to be rerun.
SUBJECT_CSV = (
    RESULTS
    / "24_Z06_EventRiskFeasibility"
    / "z06_event_feasibility_subject_level.csv"
)

# SHaRe workbook stored in the project Data directory.
XLSX = DATA / "SHaReData-FLO.xlsx"

# Canonical output directory for Step 25.
OUT = RESULTS / "25_Z06_BaselineCox"
OUT.mkdir(parents=True, exist_ok=True)

if not SUBJECT_CSV.is_file():
    raise FileNotFoundError(
        f"Step 24 subject-level output not found:\n{SUBJECT_CSV}\n"
        "Expected the existing output generated by Step 24."
    )

if not XLSX.is_file():
    raise FileNotFoundError(
        f"SHaRe workbook not found:\n{XLSX}"
    )

print(f"Project root   : {ROOT}")
print(f"Step 24 input  : {SUBJECT_CSV}")
print(f"SHaRe workbook : {XLSX}")
print(f"Step 25 output : {OUT}")


PRIMARY_ENDPOINTS = [
    "Composite_HF",
    "Atrial_Fibrillation",
    "Unplanned_CV_Hospitalization",
    "Composite_Overall",
]
EXPLORATORY_ENDPOINTS = ["Composite_VArrhythmia"]

NS = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
RNS = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"


def col_index(cell_ref: str) -> int:
    m = re.match(r"([A-Z]+)", cell_ref)
    n = 0
    for ch in m.group(1):
        n = n * 26 + ord(ch) - 64
    return n - 1


def read_xlsx_sheet_rows(path: Path, sheet_name: str):
    with zipfile.ZipFile(path) as z:
        shared = []
        if "xl/sharedStrings.xml" in z.namelist():
            root = ET.fromstring(z.read("xl/sharedStrings.xml"))
            shared = ["".join((t.text or "") for t in si.iter(f"{{{NS}}}t")) for si in root.findall(f"{{{NS}}}si")]
        wb = ET.fromstring(z.read("xl/workbook.xml"))
        rel = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
        relmap = {r.attrib["Id"]: r.attrib["Target"] for r in rel}
        target = None
        for s in wb.find(f"{{{NS}}}sheets"):
            if s.attrib.get("name") == sheet_name:
                target = relmap[s.attrib[f"{{{RNS}}}id"]]
                break
        if target is None:
            raise KeyError(sheet_name)
        target = target.lstrip("/")
        if not target.startswith("xl/"):
            target = "xl/" + target
        sheet = ET.fromstring(z.read(target))
        rows = sheet.find(f"{{{NS}}}sheetData").findall(f"{{{NS}}}row")

        def cell_value(c):
            typ = c.attrib.get("t")
            if typ == "inlineStr":
                inline = c.find(f"{{{NS}}}is")
                return "" if inline is None else "".join((t.text or "") for t in inline.iter(f"{{{NS}}}t"))
            v = c.find(f"{{{NS}}}v")
            if v is None:
                return ""
            raw = v.text or ""
            if typ == "s":
                try:
                    return shared[int(raw)]
                except Exception:
                    return raw
            return raw

        header_map = {col_index(c.attrib["r"]): cell_value(c) for c in rows[0].findall(f"{{{NS}}}c")}
        out = []
        for row in rows[1:]:
            d = {}
            for c in row.findall(f"{{{NS}}}c"):
                idx = col_index(c.attrib["r"])
                h = header_map.get(idx)
                if h:
                    d[h] = cell_value(c)
            out.append(d)
        return out


def norm_pid(x):
    try:
        return str(int(float(x)))
    except Exception:
        return str(x).strip()


def add_sex(df: pd.DataFrame) -> pd.DataFrame:
    rows = read_xlsx_sheet_rows(XLSX, "HCM_PatientKeyOutcomes")
    sex_map = {norm_pid(r.get("HCM_PatientKeyOutcomes_PID")): str(r.get("Sex", "")).strip() for r in rows}
    out = df.copy()
    out["SHaRe_PID_key"] = out["SHaRe_PID"].map(norm_pid)
    out["sex"] = out["SHaRe_PID_key"].map(sex_map)
    sex_norm = out["sex"].astype("string").str.strip().str.lower()
    out["male"] = sex_norm.map({
        "male": 1.0, "m": 1.0, "1": 1.0,
        "female": 0.0, "f": 0.0, "0": 0.0,
    }).astype(float)
    return out


def fit_cox(d: pd.DataFrame, covariates: list[str]):
    model = PHReg(d["time"].astype(float), d[covariates].astype(float), status=d["event"].astype(int), ties="breslow")
    res = model.fit()
    names = covariates
    rows = []
    for i, name in enumerate(names):
        beta = float(res.params[i])
        se = float(res.bse[i])
        p = float(res.pvalues[i])
        ci_log = np.asarray(res.conf_int())[i]
        rows.append({
            "term": name,
            "log_hr": beta,
            "se": se,
            "hr": math.exp(beta),
            "ci95_low": math.exp(float(ci_log[0])),
            "ci95_high": math.exp(float(ci_log[1])),
            "p": p,
        })
    # Simple PH diagnostic: correlation of Schoenfeld residuals with log event time.
    # Reported as a diagnostic, not as a substitute for graphical assessment.
    sr = np.asarray(res.schoenfeld_residuals)
    event_mask = d["event"].to_numpy(dtype=bool)
    et = np.log(d.loc[event_mask, "time"].to_numpy(dtype=float))
    ph = {}
    for i, name in enumerate(names):
        vals = sr[event_mask, i]
        ok = np.isfinite(vals) & np.isfinite(et)
        if ok.sum() >= 5:
            rho, pp = spearmanr(vals[ok], et[ok])
            ph[name] = (float(rho), float(pp))
        else:
            ph[name] = (np.nan, np.nan)
    return rows, ph


def endpoint_dataset(df, endpoint):
    cls_col = f"{endpoint}__baseline_class"
    evt_time_col = f"{endpoint}__time_from_baseline_years"
    # clean risk set defined at baseline
    d = df[df[cls_col].isin(["none", "incident"])].copy()
    d = d[d["baseline_to_censor_years"].notna()].copy()
    d["event"] = (d[cls_col] == "incident").astype(int)
    d["time"] = np.where(d["event"].eq(1), pd.to_numeric(d[evt_time_col], errors="coerce"), pd.to_numeric(d["baseline_to_censor_years"], errors="coerce"))
    d = d[np.isfinite(d["time"]) & (d["time"] > 0)].copy()
    return d


def main():
    df = pd.read_csv(SUBJECT_CSV)
    df = add_sex(df)
    # fixed common scaling across endpoints
    zmu = float(df["baseline_z06"].mean())
    zsd = float(df["baseline_z06"].std(ddof=1))
    if not np.isfinite(zsd) or zsd <= 0:
        raise RuntimeError(f"Invalid baseline z06 SD for standardization: {zsd}")
    df["z06_per_sd"] = (df["baseline_z06"] - zmu) / zsd
    # age per 10 years for readable coefficients; does not affect z06 estimate scale
    df["baseline_age_10y"] = pd.to_numeric(df["baseline_age"], errors="coerce") / 10.0

    all_results = []
    riskset_rows = []
    endpoints = [(x, "primary") for x in PRIMARY_ENDPOINTS] + [(x, "exploratory_sparse") for x in EXPLORATORY_ENDPOINTS]

    for endpoint, family in endpoints:
        d0 = endpoint_dataset(df, endpoint)
        # unadjusted: z06 only
        d1 = d0.dropna(subset=["z06_per_sd"]).copy()
        terms1, ph1 = fit_cox(d1, ["z06_per_sd"])
        z1 = terms1[0]
        all_results.append({
            "endpoint": endpoint, "family": family, "model": "unadjusted",
            "n": len(d1), "events": int(d1["event"].sum()),
            **z1,
            "ph_schoenfeld_spearman_rho": ph1["z06_per_sd"][0],
            "ph_schoenfeld_spearman_p": ph1["z06_per_sd"][1],
        })

        # minimally adjusted: z06 + baseline age + sex
        d2 = d0.dropna(subset=["z06_per_sd", "baseline_age_10y", "male"]).copy()
        terms2, ph2 = fit_cox(d2, ["z06_per_sd", "baseline_age_10y", "male"])
        for tr in terms2:
            if tr["term"] == "z06_per_sd":
                z2 = tr
                break
        all_results.append({
            "endpoint": endpoint, "family": family, "model": "age_sex_adjusted",
            "n": len(d2), "events": int(d2["event"].sum()),
            **z2,
            "ph_schoenfeld_spearman_rho": ph2["z06_per_sd"][0],
            "ph_schoenfeld_spearman_p": ph2["z06_per_sd"][1],
        })

        riskset_rows.append({
            "endpoint": endpoint, "family": family,
            "n_clean_positive_followup": len(d0),
            "events": int(d0["event"].sum()),
            "median_followup_or_event_time_y": float(d0["time"].median()),
            "z06_mean": float(d0["baseline_z06"].mean()),
            "z06_sd": float(d0["baseline_z06"].std(ddof=1)),
        })

    resdf = pd.DataFrame(all_results)
    # BH over the 4 primary endpoints separately by model
    resdf["q_primary4"] = np.nan
    for model_name in ["unadjusted", "age_sex_adjusted"]:
        idx = resdf.index[(resdf["family"] == "primary") & (resdf["model"] == model_name)]
        pvals = resdf.loc[idx, "p"].to_numpy(dtype=float)
        finite = np.isfinite(pvals)
        if finite.any():
            q = np.full(len(pvals), np.nan, dtype=float)
            q[finite] = multipletests(pvals[finite], method="fdr_bh")[1]
            resdf.loc[idx, "q_primary4"] = q

    resdf.to_csv(OUT / "z06_baseline_cox_results.csv", index=False)
    pd.DataFrame(riskset_rows).to_csv(OUT / "z06_baseline_cox_risksets.csv", index=False)

    # export analysis-ready rows for audit
    audit_parts = []
    for endpoint, family in endpoints:
        d = endpoint_dataset(df, endpoint).copy()
        d["endpoint"] = endpoint
        d["family"] = family
        audit_parts.append(d[["analysis_subject_key", "SHaRe_PID", "endpoint", "family", "time", "event", "baseline_z06", "z06_per_sd", "baseline_age", "sex", "male"]])
    pd.concat(audit_parts, ignore_index=True).to_csv(OUT / "z06_baseline_cox_analysis_rows.csv", index=False)

    # Robust outlier sensitivity: exclude baseline z06 with absolute robust z-score >4
    zmed = float(df["baseline_z06"].median())
    zmad = float(median_abs_deviation(df["baseline_z06"], scale="normal", nan_policy="omit"))
    if not np.isfinite(zmad) or zmad <= 0:
        raise RuntimeError(f"Invalid baseline z06 MAD for outlier sensitivity: {zmad}")
    df["z06_robust_z"] = (df["baseline_z06"] - zmed) / zmad
    sens_rows = []
    for endpoint, family in endpoints:
        ds = endpoint_dataset(df, endpoint)
        ds = ds[ds["z06_robust_z"].abs() <= 4].copy()
        for model_name, covs in [("unadjusted", ["z06_per_sd"]), ("age_sex_adjusted", ["z06_per_sd", "baseline_age_10y", "male"])]:
            dsm = ds.dropna(subset=covs).copy()
            terms, ph = fit_cox(dsm, covs)
            zterm = next(x for x in terms if x["term"] == "z06_per_sd")
            sens_rows.append({
                "endpoint": endpoint, "family": family, "model": model_name,
                "n": len(dsm), "events": int(dsm["event"].sum()),
                **zterm,
                "ph_schoenfeld_spearman_rho": ph["z06_per_sd"][0],
                "ph_schoenfeld_spearman_p": ph["z06_per_sd"][1],
                "outlier_rule": "abs robust z06 z-score <=4",
                "n_excluded_full_cohort": int((df["z06_robust_z"].abs() > 4).sum()),
            })
    sensdf = pd.DataFrame(sens_rows)
    sensdf.to_csv(OUT / "z06_baseline_cox_outlier_sensitivity.csv", index=False)

    report = []
    report.append("Step 25: baseline HCM z06 -> future events (Cox PH)\n")
    report.append(f"Common z06 standardization: mean={zmu:.6f}, SD={zsd:.6f} across n={df['baseline_z06'].notna().sum()} exact-mapped baseline subjects.\n")
    report.append("Primary multiplicity family: Composite_HF, Atrial_Fibrillation, Unplanned_CV_Hospitalization, Composite_Overall.\n")
    report.append("Composite_VArrhythmia is exploratory because of sparse incident events.\n\n")
    for _, r in resdf.iterrows():
        qtxt = f", q={r['q_primary4']:.4g}" if np.isfinite(r["q_primary4"]) else ""
        report.append(f"{r['endpoint']} | {r['model']}: n={int(r['n'])}, events={int(r['events'])}, HR per 1 SD z06={r['hr']:.3f} (95% CI {r['ci95_low']:.3f}-{r['ci95_high']:.3f}), p={r['p']:.4g}{qtxt}; PH diagnostic p={r['ph_schoenfeld_spearman_p']:.4g}\n")
    (OUT / "z06_baseline_cox_report.txt").write_text("".join(report), encoding="utf-8")
    print("".join(report))


if __name__ == "__main__":
    main()
