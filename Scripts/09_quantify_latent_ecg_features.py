def h5_dataset_inventory(h5: h5py.File) -> Dict[str, h5py.Dataset]:
    out: Dict[str, h5py.Dataset] = {}

    def visitor(name, obj):
        if isinstance(obj, h5py.Dataset):
            out[name] = obj

    h5.visititems(visitor)
    return out


def find_h5_dataset(
    inventory: Dict[str, h5py.Dataset],
    candidates: Sequence[str],
) -> Optional[h5py.Dataset]:
    # Exact path first.
    for c in candidates:
        if c in inventory:
            return inventory[c]

    # Basename, case-insensitive.
    by_base = {Path(k).name.lower(): v for k, v in inventory.items()}
    for c in candidates:
        key = Path(c).name.lower()
        if key in by_base:
            return by_base[key]

    # Substring fallback.
    for c in candidates:
        cl = c.lower()
        for name, ds in inventory.items():
            if cl in name.lower():
                return ds
    return None


def load_waveforms_and_metadata(
    h5_path: Path,
) -> Tuple[np.ndarray, Dict[str, np.ndarray], Dict[str, object]]:
    if not h5_path.exists():
        raise FileNotFoundError(f"HDF5 not found: {h5_path}")

    with h5py.File(h5_path, "r") as h5:
        inv = h5_dataset_inventory(h5)

        wave_ds = find_h5_dataset(
            inv,
            [
                "median_all_mv",
                "median_beat_all_mv",
                "median_beats_all_mv",
                "median_all",
            ],
        )
        if wave_ds is None:
            available = "\n  ".join(inv.keys())
            raise KeyError(
                "Could not find an unscaled median-beat waveform dataset. "
                "Expected a dataset such as 'median_all_mv'.\n"
                f"Available HDF5 datasets:\n  {available}"
            )

        x = np.asarray(wave_ds, dtype=np.float64)

        if x.ndim != 3:
            raise ValueError(f"Waveform dataset must be 3D; got shape {x.shape}")

        # Standardize to [N, 12, T].
        if x.shape[1] == 12:
            pass
        elif x.shape[2] == 12:
            x = np.transpose(x, (0, 2, 1))
        else:
            raise ValueError(f"Cannot identify 12-lead axis in waveform shape {x.shape}")

        n = x.shape[0]

        metadata: Dict[str, np.ndarray] = {}
        wanted = [
            "ecg_id", "subject_id", "patient_id", "source", "cohort",
            "label", "is_hcm", "target", "y",
            "split", "set", "partition", "subset", "group",
            "dataset_split", "split_name", "sample_split", "phase1_split",
            "normal_train", "normal_val", "normal_test",
            "normal_train_mask", "normal_val_mask", "normal_test_mask",
            "hcm", "hcm_eval", "hcm_mask", "hcm_eval_mask",
            "age", "sex", "gender",
            "median_rr_ms", "rr_ms", "heart_rate_bpm", "hr_bpm",
            "n_usable_beats", "qc", "quality",
        ]

        for key in wanted:
            ds = find_h5_dataset(inv, [key])
            if ds is not None:
                arr = decode_array(np.asarray(ds))
                if arr.ndim == 1 and len(arr) == n:
                    metadata[key] = arr

        # Also retain every 1-D per-record dataset. This makes the script
        # robust to project-specific names such as split_code, cohort_name,
        # normal_train_mask, etc.
        for name, ds in inv.items():
            base = Path(name).name
            if base in metadata:
                continue
            try:
                arr = decode_array(np.asarray(ds))
            except Exception:
                continue
            if arr.ndim == 1 and len(arr) == n:
                metadata[base] = arr

        # Recover split membership from HDF5 index arrays or masks.
        index_memberships = {}
        membership_tokens = {
            "normal_train": ("normal_train", "train_normal"),
            "normal_val": ("normal_val", "normal_validation", "val_normal"),
            "normal_test": ("normal_test", "test_normal"),
            "hcm": ("hcm_eval", "hcm_test", "hcm_indices", "hcm_index"),
        }

        for group_name, tokens in membership_tokens.items():
            for name, ds in inv.items():
                lname = name.lower()
                if not any(tok in lname for tok in tokens):
                    continue

                try:
                    arr = np.asarray(ds)
                except Exception:
                    continue

                if arr.ndim != 1:
                    continue

                # Per-record Boolean / 0-1 mask.
                if len(arr) == n:
                    try:
                        vals = np.asarray(arr, dtype=float)
                        finite = vals[np.isfinite(vals)]
                        uniq = set(np.unique(finite).tolist())
                        if uniq.issubset({0.0, 1.0}):
                            index_memberships[group_name] = vals.astype(bool)
                            break
                    except Exception:
                        pass

                # Explicit retained-row indices.
                if np.issubdtype(arr.dtype, np.integer) and 0 < len(arr) < n:
                    idx = np.asarray(arr, dtype=int)
                    if len(idx) and np.min(idx) >= 0 and np.max(idx) < n:
                        mask = np.zeros(n, dtype=bool)
                        mask[idx] = True
                        index_memberships[group_name] = mask
                        break

        for group_name, mask in index_memberships.items():
            metadata[f"__membership_{group_name}"] = mask

        attrs: Dict[str, object] = {}
        for k, v in h5.attrs.items():
            try:
                if isinstance(v, bytes):
                    attrs[k] = v.decode("utf-8")
                elif np.isscalar(v):
                    attrs[k] = v.item() if hasattr(v, "item") else v
                else:
                    attrs[k] = np.asarray(v).tolist()
            except Exception:
                attrs[k] = str(v)

    return x, metadata, attrs


