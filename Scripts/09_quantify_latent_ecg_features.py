def decode_array(arr: np.ndarray) -> np.ndarray:
    """Decode byte-string arrays to regular Python/NumPy strings."""
    a = np.asarray(arr)
    if a.dtype.kind in ("S", "O"):
        flat = []
        for x in a.ravel():
            if isinstance(x, bytes):
                flat.append(x.decode("utf-8", errors="replace"))
            else:
                flat.append(str(x))
        return np.asarray(flat, dtype=object).reshape(a.shape)
    return a


def normalize_latent_name(name: str) -> str:
    """z0 / z_0 / z00 / z_00 -> z_00."""
    m = re.fullmatch(r"z_?(\d+)", str(name).strip(), flags=re.IGNORECASE)
    if not m:
        return str(name)
    return f"z_{int(m.group(1)):02d}"


def latent_columns(df: pd.DataFrame) -> List[str]:
    cols = []
    for c in df.columns:
        if re.fullmatch(r"z_?\d+", str(c), flags=re.IGNORECASE):
            cols.append(c)
    cols = sorted(cols, key=lambda x: int(re.findall(r"\d+", str(x))[0]))
    return cols


def bh_fdr(pvalues: Sequence[float]) -> np.ndarray:
    """Benjamini-Hochberg FDR q-values; NaNs remain NaN."""
    p = np.asarray(pvalues, dtype=float)
    q = np.full_like(p, np.nan, dtype=float)
    ok = np.isfinite(p)
    if not np.any(ok):
        return q

    pv = p[ok]
    order = np.argsort(pv)
    ranked = pv[order]
    m = len(ranked)

    adjusted = ranked * m / np.arange(1, m + 1, dtype=float)
    adjusted = np.minimum.accumulate(adjusted[::-1])[::-1]
    adjusted = np.clip(adjusted, 0.0, 1.0)

    tmp = np.empty_like(adjusted)
    tmp[order] = adjusted
    q[ok] = tmp
    return q


def safe_pearson(x: np.ndarray, y: np.ndarray) -> Tuple[float, float, int]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    n = int(ok.sum())
    if n < 5 or np.nanstd(x[ok]) < EPS or np.nanstd(y[ok]) < EPS:
        return np.nan, np.nan, n
    r, p = stats.pearsonr(x[ok], y[ok])
    return float(r), float(p), n


def safe_spearman(x: np.ndarray, y: np.ndarray) -> Tuple[float, float, int]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    n = int(ok.sum())
    if n < 5 or np.nanstd(x[ok]) < EPS or np.nanstd(y[ok]) < EPS:
        return np.nan, np.nan, n
    r, p = stats.spearmanr(x[ok], y[ok])
    return float(r), float(p), n


def standardized_linear_slope(x: np.ndarray, y: np.ndarray) -> Tuple[float, float, float, int]:
    """
    Returns standardized slope, raw slope, p-value, n.
    Standardized slope equals Pearson r in a one-predictor model, but raw slope
    is useful because z is approximately measured in latent units.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    n = int(ok.sum())
    if n < 5 or np.std(x[ok]) < EPS or np.std(y[ok]) < EPS:
        return np.nan, np.nan, np.nan, n

    res = stats.linregress(x[ok], y[ok])
    xz = (x[ok] - np.mean(x[ok])) / np.std(x[ok], ddof=1)
    yz = (y[ok] - np.mean(y[ok])) / np.std(y[ok], ddof=1)
    resz = stats.linregress(xz, yz)
    return float(resz.slope), float(res.slope), float(res.pvalue), n


