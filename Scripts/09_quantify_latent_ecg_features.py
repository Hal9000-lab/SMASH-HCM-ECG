def candidate_feature_columns(df: pd.DataFrame) -> List[str]:
    """
    Keep continuous morphology descriptors; exclude administrative/QC/index columns
    and discrete polarity flags from the primary correlation analysis.
    """
    exclude_exact = {
        "feature_extraction_ok",
        "qrs_on_idx", "qrs_off_idx", "qrs_peak_energy_idx",
        "qrs_boundary_qc", "Tend_est_qc",
    }

    cols = []
    for c in df.columns:
        if c in exclude_exact:
            continue
        if c.startswith("baseline_mV_"):
            continue
        if c.startswith("T_polarity_"):
            continue
        if c.endswith("_idx"):
            continue
        if c in {"QRS_axis_deg"}:
            # Circular; use sin/cos instead.
            continue
        if pd.api.types.is_numeric_dtype(df[c]):
            vals = pd.to_numeric(df[c], errors="coerce").to_numpy(dtype=float)
            if np.isfinite(vals).sum() >= 20 and np.nanstd(vals) > EPS:
                cols.append(c)
    return cols


def association_table(
    df: pd.DataFrame,
    mask: np.ndarray,
    zcols: Sequence[str],
    feature_cols: Sequence[str],
    group_name: str,
) -> pd.DataFrame:
    sub = df.loc[mask].copy()
    rows = []

    for z in zcols:
        zval = pd.to_numeric(sub[z], errors="coerce").to_numpy(dtype=float)
        for feat in feature_cols:
            fval = pd.to_numeric(sub[feat], errors="coerce").to_numpy(dtype=float)

            pr, pp, n1 = safe_pearson(zval, fval)
            sr, sp, n2 = safe_spearman(zval, fval)
            beta_std, beta_raw, lp, n3 = standardized_linear_slope(zval, fval)

            rows.append({
                "group": group_name,
                "latent": z,
                "feature": feat,
                "n": min(n1, n2, n3),
                "pearson_r": pr,
                "pearson_p": pp,
                "spearman_rho": sr,
                "spearman_p": sp,
                "beta_standardized": beta_std,
                "beta_raw_feature_per_latent_unit": beta_raw,
                "linear_p": lp,
            })

    out = pd.DataFrame(rows)
    if len(out):
        out["pearson_q_fdr"] = bh_fdr(out["pearson_p"].to_numpy())
        out["spearman_q_fdr"] = bh_fdr(out["spearman_p"].to_numpy())
        out["linear_q_fdr"] = bh_fdr(out["linear_p"].to_numpy())
        out["abs_spearman_rho"] = np.abs(out["spearman_rho"])
        out = out.sort_values(
            ["latent", "abs_spearman_rho"],
            ascending=[True, False],
        ).reset_index(drop=True)
    return out


def top_associations(
    assoc_tables: Dict[str, pd.DataFrame],
    top_n: int,
) -> pd.DataFrame:
    blocks = []
    for group, tab in assoc_tables.items():
        if tab.empty:
            continue
        for z, zz in tab.groupby("latent"):
            blocks.append(
                zz.sort_values("abs_spearman_rho", ascending=False).head(top_n)
            )
    if not blocks:
        return pd.DataFrame()
    return pd.concat(blocks, ignore_index=True)


