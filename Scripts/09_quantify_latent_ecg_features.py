def extract_all_record_features(
    waveforms: np.ndarray,
    base_df: pd.DataFrame,
    fs: float,
    pre_ms: float,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    n = waveforms.shape[0]
    rr_col = find_rr_column(base_df)

    rows = []
    qc_rows = []

    for i in range(n):
        if i % 250 == 0 or i == n - 1:
            print(f"[features] {i + 1}/{n}")

        rr = None
        if rr_col is not None:
            rr_val = pd.to_numeric(pd.Series([base_df.iloc[i][rr_col]]), errors="coerce").iloc[0]
            if np.isfinite(rr_val):
                rr = float(rr_val)

        x = waveforms[i]
        finite_fraction = float(np.isfinite(x).mean())

        if finite_fraction < 0.995:
            row = {
                "feature_extraction_ok": 0,
                "feature_error": f"finite_fraction={finite_fraction:.4f}",
            }
            rows.append(row)
            qc_rows.append({
                "row_index": i,
                "finite_fraction": finite_fraction,
                "feature_extraction_ok": 0,
                "feature_error": row["feature_error"],
            })
            continue

        try:
            feat = extract_ecg_features(
                x=x,
                fs=fs,
                pre_ms=pre_ms,
                rr_ms=rr,
                lead_names=DEFAULT_LEADS,
            )
            feat["feature_extraction_ok"] = 1
            feat["feature_error"] = ""
        except Exception as e:
            feat = {
                "feature_extraction_ok": 0,
                "feature_error": f"{type(e).__name__}: {e}",
            }

        rows.append(feat)
        qc_rows.append({
            "row_index": i,
            "finite_fraction": finite_fraction,
            "feature_extraction_ok": int(feat.get("feature_extraction_ok", 0)),
            "feature_error": feat.get("feature_error", ""),
            "qrs_boundary_qc": feat.get("qrs_boundary_qc", np.nan),
            "qrs_boundary_method": feat.get("qrs_boundary_method", ""),
            "qrs_duration_ms": feat.get("qrs_duration_ms", np.nan),
            "Tend_est_qc": feat.get("Tend_est_qc", np.nan),
        })

    feat_df = pd.DataFrame(rows)
    qc_df = pd.DataFrame(qc_rows)
    return feat_df, qc_df


