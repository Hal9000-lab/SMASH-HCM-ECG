def time_axis_ms(n_samples: int, fs: float, pre_ms: float) -> np.ndarray:
    return pre_ms + np.arange(n_samples, dtype=float) * 1000.0 / fs


def idx_range(t_ms: np.ndarray, lo: float, hi: float) -> np.ndarray:
    return np.where((t_ms >= lo) & (t_ms <= hi))[0]


def robust_mad(x: np.ndarray) -> float:
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if len(x) == 0:
        return np.nan
    med = np.median(x)
    return float(1.4826 * np.median(np.abs(x - med)))


def baseline_correct_record(x: np.ndarray, t_ms: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """
    Per-lead baseline correction.

    Uses two short candidate TP-like windows:
      early: -345 to -300 ms
      late : +570 to +635 ms
    and chooses the lower-variability candidate per lead.
    """
    early = idx_range(t_ms, -345.0, -300.0)
    late = idx_range(t_ms, 570.0, 635.0)

    y = np.asarray(x, dtype=float).copy()
    baselines = np.zeros(y.shape[0], dtype=float)

    for l in range(y.shape[0]):
        candidates = []
        for w in (early, late):
            if len(w) >= 3:
                vals = y[l, w]
                vals = vals[np.isfinite(vals)]
                if len(vals) >= 3:
                    candidates.append((robust_mad(vals), float(np.median(vals))))
        if candidates:
            candidates.sort(key=lambda z: np.inf if not np.isfinite(z[0]) else z[0])
            baseline = candidates[0][1]
        else:
            baseline = float(np.nanmedian(y[l]))
        baselines[l] = baseline
        y[l] -= baseline

    return y, baselines


def qrs_energy_envelope(y: np.ndarray, fs: float, t_ms: np.ndarray) -> np.ndarray:
    """
    Multilead normalized derivative-energy envelope.

    Leadwise normalization is only used for QRS boundary detection. It does not
    alter the amplitudes used for morphology features.
    """
    dy = np.gradient(y, axis=1) * fs

    qwin = idx_range(t_ms, -120.0, 160.0)
    if len(qwin) == 0:
        qwin = np.arange(y.shape[1])

    scales = np.nanpercentile(np.abs(dy[:, qwin]), 95, axis=1)
    scales = np.where(np.isfinite(scales) & (scales > EPS), scales, 1.0)

    dn = dy / scales[:, None]
    env = np.sqrt(np.nanmean(dn ** 2, axis=0))
    smooth_samples = max(1, int(round(0.008 * fs)))  # ~8 ms
    env = uniform_filter1d(env, size=smooth_samples, mode="nearest")
    return env


def _find_sustained_below_backward(
    env: np.ndarray,
    peak_idx: int,
    start_idx: int,
    threshold: float,
    sustain: int,
) -> Optional[int]:
    for i in range(peak_idx - 1, start_idx + sustain - 1, -1):
        a = max(start_idx, i - sustain + 1)
        b = i + 1
        if (b - a) >= sustain and np.all(env[a:b] < threshold):
            return i + 1
    return None


def _find_sustained_below_forward(
    env: np.ndarray,
    peak_idx: int,
    end_idx: int,
    threshold: float,
    sustain: int,
) -> Optional[int]:
    for i in range(peak_idx + 1, end_idx - sustain + 2):
        a = i
        b = min(end_idx + 1, i + sustain)
        if (b - a) >= sustain and np.all(env[a:b] < threshold):
            return i
    return None


def delineate_qrs(
    y: np.ndarray,
    fs: float,
    t_ms: np.ndarray,
) -> Dict[str, object]:
    """
    Estimate one common QRS onset/offset for all 12 leads.

    Returns a conservative fallback window if the envelope estimate is implausible.
    """
    env = qrs_energy_envelope(y, fs, t_ms)

    peak_win = idx_range(t_ms, -80.0, 100.0)
    if len(peak_win) == 0:
        raise RuntimeError("QRS peak search window is empty.")
    peak_idx = int(peak_win[np.argmax(env[peak_win])])

    noise_win = idx_range(t_ms, -290.0, -150.0)
    if len(noise_win) < 5:
        noise_win = idx_range(t_ms, -340.0, -180.0)

    noise = env[noise_win]
    noise_med = float(np.nanmedian(noise))
    noise_mad = robust_mad(noise)
    if not np.isfinite(noise_mad):
        noise_mad = 0.0

    peak_val = float(env[peak_idx])
    threshold = max(
        noise_med + 5.0 * noise_mad,
        noise_med + 0.08 * max(peak_val - noise_med, 0.0),
    )

    on_search = idx_range(t_ms, -140.0, 0.0)
    off_search = idx_range(t_ms, 0.0, 180.0)
    on_start = int(on_search[0]) if len(on_search) else max(0, peak_idx - int(0.14 * fs))
    off_end = int(off_search[-1]) if len(off_search) else min(len(env) - 1, peak_idx + int(0.18 * fs))

    sustain = max(2, int(round(0.010 * fs)))  # 10 ms

    onset = _find_sustained_below_backward(env, peak_idx, on_start, threshold, sustain)
    offset = _find_sustained_below_forward(env, peak_idx, off_end, threshold, sustain)

    qc = True
    method = "multilead_gradient_energy"

    if onset is None or offset is None or offset <= onset:
        qc = False
    else:
        dur = (offset - onset) * 1000.0 / fs
        if not (45.0 <= dur <= 180.0):
            qc = False

    if not qc:
        # Conservative fixed fallback around the aligned R reference.
        on_candidates = idx_range(t_ms, -60.0, -55.0)
        off_candidates = idx_range(t_ms, 95.0, 105.0)
        onset = int(on_candidates[len(on_candidates)//2]) if len(on_candidates) else peak_idx - int(0.06 * fs)
        offset = int(off_candidates[len(off_candidates)//2]) if len(off_candidates) else peak_idx + int(0.10 * fs)
        onset = max(0, onset)
        offset = min(len(env) - 1, offset)
        method = "fallback_fixed_-60_+100ms"

    return {
        "qrs_on_idx": int(onset),
        "qrs_off_idx": int(offset),
        "qrs_peak_energy_idx": int(peak_idx),
        "qrs_on_ms": float(t_ms[onset]),
        "qrs_off_ms": float(t_ms[offset]),
        "qrs_duration_ms": float((offset - onset) * 1000.0 / fs),
        "qrs_boundary_qc": int(qc),
        "qrs_boundary_method": method,
        "qrs_energy_peak": peak_val,
        "qrs_energy_threshold": float(threshold),
    }


def lead_qrs_features(
    sig: np.ndarray,
    onset: int,
    offset: int,
    fs: float,
) -> Dict[str, float]:
    seg = np.asarray(sig[onset:offset + 1], dtype=float)

    if len(seg) < 5 or not np.any(np.isfinite(seg)):
        return {k: np.nan for k in [
            "R_mV", "S_mV", "S_depth_mV", "Q_mV", "Q_depth_mV", "Q_duration_ms",
            "Q_R_ratio", "R_S_ratio", "QRS_p2p_mV", "QRS_net_area_mVms",
            "QRS_abs_area_mVms"
        ]}

    # Use the dominant positive peak as R. If the entire complex is negative,
    # R amplitude is clipped at 0 rather than forcing an artificial positive R.
    r_rel = int(np.nanargmax(seg))
    r_raw = float(seg[r_rel])
    r_amp = max(0.0, r_raw)

    post_r = seg[r_rel:]
    s_amp = float(np.nanmin(post_r)) if len(post_r) else np.nan
    s_depth = max(0.0, -s_amp) if np.isfinite(s_amp) else np.nan

    # Initial Q: negative deflection preceding the dominant positive R.
    q_amp = np.nan
    q_depth = 0.0
    q_dur = 0.0

    if r_rel >= 2 and r_amp > 0.02:
        pre_r = seg[:r_rel + 1]
        q_rel = int(np.nanargmin(pre_r))
        q_candidate = float(pre_r[q_rel])

        if q_candidate < -0.005:
            q_amp = q_candidate
            q_depth = -q_candidate

            # Duration of contiguous negative samples around Q nadir.
            a = q_rel
            while a > 0 and pre_r[a - 1] < 0:
                a -= 1
            b = q_rel
            while b + 1 < len(pre_r) and pre_r[b + 1] < 0:
                b += 1
            q_dur = (b - a + 1) * 1000.0 / fs

    rs_ratio = r_amp / (s_depth + 1e-6)
    qr_ratio = q_depth / (r_amp + 1e-6) if r_amp > 0 else np.nan

    dt_ms = 1000.0 / fs
    net_area = float(np.trapezoid(seg, dx=dt_ms))
    abs_area = float(np.trapezoid(np.abs(seg), dx=dt_ms))

    return {
        "R_mV": r_amp,
        "S_mV": s_amp,
        "S_depth_mV": s_depth,
        "Q_mV": q_amp,
        "Q_depth_mV": q_depth,
        "Q_duration_ms": q_dur,
        "Q_R_ratio": qr_ratio,
        "R_S_ratio": rs_ratio,
        "QRS_p2p_mV": float(np.nanmax(seg) - np.nanmin(seg)),
        "QRS_net_area_mVms": net_area,
        "QRS_abs_area_mVms": abs_area,
    }


def estimate_tend_global(
    y: np.ndarray,
    t_ms: np.ndarray,
    qrs_off_idx: int,
    tpeak_idx: int,
    fs: float,
    search_end_ms: float,
) -> Tuple[float, int]:
    """
    Conservative research-only T-end surrogate based on the smoothed global
    vector-magnitude envelope returning toward baseline after the T peak.

    Returns (Tend time relative to R in ms, QC flag).
    """
    env = np.sqrt(np.nanmean(y ** 2, axis=0))
    env = uniform_filter1d(env, size=max(2, int(round(0.020 * fs))), mode="nearest")

    baseline_idx = idx_range(t_ms, -300.0, -160.0)
    if len(baseline_idx) < 5:
        return np.nan, 0

    base = env[baseline_idx]
    base_med = float(np.nanmedian(base))
    base_mad = robust_mad(base)
    if not np.isfinite(base_mad):
        base_mad = 0.0

    if tpeak_idx <= qrs_off_idx or tpeak_idx >= len(env):
        return np.nan, 0

    peak_amp = float(env[tpeak_idx])
    threshold = max(
        base_med + 3.0 * base_mad,
        base_med + 0.10 * max(peak_amp - base_med, 0.0),
    )

    end_candidates = np.where(t_ms <= search_end_ms)[0]
    if len(end_candidates) == 0:
        return np.nan, 0
    end_idx = int(end_candidates[-1])

    sustain = max(3, int(round(0.024 * fs)))  # ~24 ms
    for i in range(tpeak_idx + 1, end_idx - sustain + 2):
        if np.all(env[i:i + sustain] < threshold):
            return float(t_ms[i]), 1

    return np.nan, 0


def extract_ecg_features(
    x: np.ndarray,
    fs: float,
    pre_ms: float,
    rr_ms: Optional[float] = None,
    lead_names: Sequence[str] = DEFAULT_LEADS,
) -> Dict[str, object]:
    """
    Extract ECG morphology descriptors from one 12-lead representative median beat.
    Input x must be [12, T] in mV.
    """
    x = np.asarray(x, dtype=float)
    if x.ndim != 2 or x.shape[0] != 12:
        raise ValueError(f"Expected [12,T], got {x.shape}")

    n_samples = x.shape[1]
    t_ms = time_axis_ms(n_samples, fs, pre_ms)
    y, baselines = baseline_correct_record(x, t_ms)

    out: Dict[str, object] = {}
    qrs = delineate_qrs(y, fs, t_ms)
    out.update(qrs)

    onset = int(qrs["qrs_on_idx"])
    offset = int(qrs["qrs_off_idx"])

    # Leadwise QRS morphology.
    qrs_by_lead: Dict[str, Dict[str, float]] = {}
    for li, lead in enumerate(lead_names):
        f = lead_qrs_features(y[li], onset, offset, fs)
        qrs_by_lead[lead] = f
        for k, v in f.items():
            out[f"{k}_{lead}"] = v
        out[f"baseline_mV_{lead}"] = float(baselines[li])

    # Common classical voltage descriptors.
    out["SokolowLyon_mV"] = (
        qrs_by_lead["V1"]["S_depth_mV"]
        + max(qrs_by_lead["V5"]["R_mV"], qrs_by_lead["V6"]["R_mV"])
    )
    out["CornellLike_mV"] = (
        qrs_by_lead["aVL"]["R_mV"]
        + qrs_by_lead["V3"]["S_depth_mV"]
    )

    # QRS frontal axis from net QRS areas in I and aVF.
    area_i = qrs_by_lead["I"]["QRS_net_area_mVms"]
    area_avf = qrs_by_lead["aVF"]["QRS_net_area_mVms"]
    axis_rad = math.atan2(area_avf, area_i)
    axis_deg = math.degrees(axis_rad)
    out["QRS_axis_deg"] = axis_deg
    out["QRS_axis_sin"] = math.sin(axis_rad)
    out["QRS_axis_cos"] = math.cos(axis_rad)

    # Precordial R/S transition. Continuous values 1...6; NaN if no crossing.
    rs_vals = [qrs_by_lead[f"V{i}"]["R_S_ratio"] for i in range(1, 7)]
    out["RS_transition_lead"] = np.nan
    for i, val in enumerate(rs_vals, start=1):
        if np.isfinite(val) and val >= 1.0:
            out["RS_transition_lead"] = float(i)
            break

    # Global QRS amplitude / area summaries.
    qrs_seg = y[:, onset:offset + 1]
    out["QRS_global_rms_mV"] = float(np.sqrt(np.nanmean(qrs_seg ** 2)))
    out["QRS_global_p2p_mV"] = float(np.nanmax(qrs_seg) - np.nanmin(qrs_seg))
    out["QRS_global_abs_area_mVms"] = float(
        np.trapezoid(np.sqrt(np.nanmean(qrs_seg ** 2, axis=0)), dx=1000.0 / fs)
    )

    # ST segment: point and mean around J+60 ms.
    j_ms = float(qrs["qrs_off_ms"])
    st_center_ms = j_ms + 60.0
    st_mean_lo = j_ms + 40.0
    st_mean_hi = j_ms + 80.0

    for li, lead in enumerate(lead_names):
        st_idx = int(np.argmin(np.abs(t_ms - st_center_ms)))
        st_win = idx_range(t_ms, st_mean_lo, st_mean_hi)
        out[f"ST60_mV_{lead}"] = float(y[li, st_idx])
        out[f"ST40_80_mean_mV_{lead}"] = (
            float(np.nanmean(y[li, st_win])) if len(st_win) else np.nan
        )

    # T-wave search end adapted to RR when available to reduce contamination
    # from the following beat.
    search_end_ms = 520.0
    if rr_ms is not None and np.isfinite(rr_ms) and rr_ms > 0:
        search_end_ms = min(search_end_ms, 0.75 * float(rr_ms))
        search_end_ms = max(search_end_ms, 260.0)

    t_start_ms = max(j_ms + 50.0, 90.0)
    t_idx = idx_range(t_ms, t_start_ms, search_end_ms)

    tpeak_times = []
    tpeak_weights = []

    for li, lead in enumerate(lead_names):
        if len(t_idx) < 5:
            out[f"T_amp_mV_{lead}"] = np.nan
            out[f"T_abs_amp_mV_{lead}"] = np.nan
            out[f"T_peak_ms_{lead}"] = np.nan
            out[f"T_area_mVms_{lead}"] = np.nan
            out[f"T_polarity_{lead}"] = np.nan
            continue

        vals = y[li, t_idx]
        rel = int(np.nanargmax(np.abs(vals)))
        peak_idx = int(t_idx[rel])
        amp = float(y[li, peak_idx])

        out[f"T_amp_mV_{lead}"] = amp
        out[f"T_abs_amp_mV_{lead}"] = abs(amp)
        out[f"T_peak_ms_{lead}"] = float(t_ms[peak_idx])
        out[f"T_area_mVms_{lead}"] = float(np.trapezoid(vals, dx=1000.0 / fs))
        out[f"T_polarity_{lead}"] = float(np.sign(amp)) if abs(amp) > 0.01 else 0.0

        tpeak_times.append(float(t_ms[peak_idx]))
        tpeak_weights.append(abs(amp))

    # Global T peak from multilead vector magnitude.
    if len(t_idx) >= 5:
        t_env = np.sqrt(np.nanmean(y[:, t_idx] ** 2, axis=0))
        rel = int(np.nanargmax(t_env))
        global_tpeak_idx = int(t_idx[rel])
        global_tpeak_ms = float(t_ms[global_tpeak_idx])
        out["T_global_peak_ms"] = global_tpeak_ms
        out["T_global_rms_peak_mV"] = float(t_env[rel])

        qtpeak = global_tpeak_ms - float(qrs["qrs_on_ms"])
        out["QTpeak_global_ms"] = qtpeak

        if rr_ms is not None and np.isfinite(rr_ms) and rr_ms > 0:
            rr_s = float(rr_ms) / 1000.0
            out["QTpeakc_Bazett_ms"] = qtpeak / math.sqrt(rr_s)
            out["QTpeakc_Fridericia_ms"] = qtpeak / (rr_s ** (1.0 / 3.0))
        else:
            out["QTpeakc_Bazett_ms"] = np.nan
            out["QTpeakc_Fridericia_ms"] = np.nan

        tend_ms, tend_qc = estimate_tend_global(
            y, t_ms, offset, global_tpeak_idx, fs, search_end_ms
        )
        out["Tend_global_ms_est"] = tend_ms
        out["Tend_est_qc"] = int(tend_qc)

        if np.isfinite(tend_ms):
            qt_est = tend_ms - float(qrs["qrs_on_ms"])
            out["QT_global_ms_est"] = qt_est
            if rr_ms is not None and np.isfinite(rr_ms) and rr_ms > 0:
                rr_s = float(rr_ms) / 1000.0
                out["QTc_Bazett_ms_est"] = qt_est / math.sqrt(rr_s)
                out["QTc_Fridericia_ms_est"] = qt_est / (rr_s ** (1.0 / 3.0))
            else:
                out["QTc_Bazett_ms_est"] = np.nan
                out["QTc_Fridericia_ms_est"] = np.nan
        else:
            out["QT_global_ms_est"] = np.nan
            out["QTc_Bazett_ms_est"] = np.nan
            out["QTc_Fridericia_ms_est"] = np.nan
    else:
        for k in [
            "T_global_peak_ms", "T_global_rms_peak_mV", "QTpeak_global_ms",
            "QTpeakc_Bazett_ms", "QTpeakc_Fridericia_ms",
            "Tend_global_ms_est", "QT_global_ms_est",
            "QTc_Bazett_ms_est", "QTc_Fridericia_ms_est",
        ]:
            out[k] = np.nan
        out["Tend_est_qc"] = 0

    # Global T/QRS morphology balance.
    if len(t_idx) >= 5:
        t_rms = float(np.sqrt(np.nanmean(y[:, t_idx] ** 2)))
        out["T_global_rms_mV"] = t_rms
        out["T_to_QRS_rms_ratio"] = t_rms / (out["QRS_global_rms_mV"] + EPS)
    else:
        out["T_global_rms_mV"] = np.nan
        out["T_to_QRS_rms_ratio"] = np.nan

    return out


