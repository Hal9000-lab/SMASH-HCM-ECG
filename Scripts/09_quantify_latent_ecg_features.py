def choose_heatmap_features(
    assoc: pd.DataFrame,
    max_features: int,
) -> List[str]:
    if assoc.empty:
        return []

    # Prioritize conventional clinically interpretable descriptors.
    preferred = [
        "qrs_duration_ms",
        "QRS_axis_sin", "QRS_axis_cos",
        "R_mV_I", "R_mV_aVL", "R_mV_V5", "R_mV_V6",
        "S_depth_mV_V1", "S_depth_mV_V2", "S_depth_mV_V3",
        "SokolowLyon_mV", "CornellLike_mV",
        "R_S_ratio_V1", "R_S_ratio_V2", "R_S_ratio_V5", "RS_transition_lead",
        "Q_depth_mV_I", "Q_depth_mV_aVL",
        "Q_depth_mV_II", "Q_depth_mV_III", "Q_depth_mV_aVF",
        "ST60_mV_I", "ST60_mV_aVL", "ST60_mV_V5",
        "T_amp_mV_I", "T_amp_mV_aVL", "T_amp_mV_II",
        "T_amp_mV_III", "T_amp_mV_aVF", "T_amp_mV_V4", "T_amp_mV_V5",
        "T_global_peak_ms", "QTpeak_global_ms",
        "QTpeakc_Fridericia_ms",
        "T_to_QRS_rms_ratio",
    ]

    available = set(assoc["feature"].unique())
    chosen = [x for x in preferred if x in available]

    if len(chosen) < max_features:
        extra = (
            assoc.groupby("feature")["abs_spearman_rho"]
            .max()
            .sort_values(ascending=False)
            .index.tolist()
        )
        for f in extra:
            if f not in chosen:
                chosen.append(f)
            if len(chosen) >= max_features:
                break

    return chosen[:max_features]


def plot_association_heatmap(
    assoc: pd.DataFrame,
    out_path: Path,
    title: str,
    max_features: int,
) -> None:
    if assoc.empty:
        return

    features = choose_heatmap_features(assoc, max_features)
    latents = sorted(
        assoc["latent"].unique(),
        key=lambda z: int(re.findall(r"\d+", z)[0]),
    )

    mat = np.full((len(features), len(latents)), np.nan)
    for i, feat in enumerate(features):
        for j, z in enumerate(latents):
            rr = assoc[(assoc["feature"] == feat) & (assoc["latent"] == z)]
            if len(rr):
                mat[i, j] = rr.iloc[0]["spearman_rho"]

    fig_w = max(10.0, 0.65 * len(latents))
    fig_h = max(8.0, 0.34 * len(features) + 2.0)

    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    im = ax.imshow(mat, aspect="auto", vmin=-1.0, vmax=1.0)
    ax.set_xticks(np.arange(len(latents)))
    ax.set_xticklabels(latents, rotation=45, ha="right")
    ax.set_yticks(np.arange(len(features)))
    ax.set_yticklabels(features)
    ax.set_xlabel("Latent coordinate")
    ax.set_ylabel("ECG feature")
    ax.set_title(title)

    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Spearman rho")

    fig.tight_layout()
    fig.savefig(out_path, dpi=180, bbox_inches="tight")
    plt.close(fig)


def plot_traversal_slope_heatmap(
    slopes: pd.DataFrame,
    out_path: Path,
    max_features: int,
) -> None:
    if slopes.empty:
        return

    # Use features showing strong standardized evidence of monotonic traversal.
    tmp = slopes.copy()
    # Normalize slopes feature-wise so units do not dominate the visualization.
    pivot_raw = tmp.pivot_table(
        index="feature", columns="latent", values="slope_per_sd", aggfunc="first"
    )

    # Rank features by maximum |r| * sqrt(R^2) effectively monotonicity + effect.
    rank = (
        tmp.assign(score=np.abs(tmp["r_value"]))
        .groupby("feature")["score"]
        .max()
        .sort_values(ascending=False)
    )

    preferred = [
        "R_mV_I", "R_mV_aVL", "R_mV_V5", "R_mV_V6",
        "S_depth_mV_V1", "S_depth_mV_V2", "S_depth_mV_V3",
        "SokolowLyon_mV", "CornellLike_mV",
        "QRS_axis_sin", "QRS_axis_cos",
        "RS_transition_lead",
        "ST60_mV_aVL", "ST60_mV_V5",
        "T_amp_mV_I", "T_amp_mV_aVL", "T_amp_mV_III",
        "T_amp_mV_aVF", "T_amp_mV_V5",
        "T_global_peak_ms", "QTpeak_global_ms",
    ]

    features = [f for f in preferred if f in pivot_raw.index]
    for f in rank.index:
        if f not in features:
            features.append(f)
        if len(features) >= max_features:
            break
    features = features[:max_features]

    latents = sorted(
        pivot_raw.columns,
        key=lambda z: int(re.findall(r"\d+", z)[0]),
    )

    mat = np.full((len(features), len(latents)), np.nan)
    for i, feat in enumerate(features):
        vals = pivot_raw.loc[feat, latents].to_numpy(dtype=float)
        scale = np.nanmax(np.abs(vals))
        if np.isfinite(scale) and scale > EPS:
            vals = vals / scale
        mat[i, :] = vals

    fig_w = max(10.0, 0.65 * len(latents))
    fig_h = max(8.0, 0.34 * len(features) + 2.0)

    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    im = ax.imshow(mat, aspect="auto", vmin=-1.0, vmax=1.0)
    ax.set_xticks(np.arange(len(latents)))
    ax.set_xticklabels(latents, rotation=45, ha="right")
    ax.set_yticks(np.arange(len(features)))
    ax.set_yticklabels(features)
    ax.set_xlabel("Latent coordinate")
    ax.set_ylabel("ECG feature")
    ax.set_title("Latent traversal sensitivity (feature-wise normalized slope)")

    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Normalized d(feature)/d(z SD)")

    fig.tight_layout()
    fig.savefig(out_path, dpi=180, bbox_inches="tight")
    plt.close(fig)


