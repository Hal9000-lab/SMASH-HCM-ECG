def _first_key(npz, candidates: Sequence[str]) -> Optional[str]:
    lower = {k.lower(): k for k in npz.files}
    for c in candidates:
        if c.lower() in lower:
            return lower[c.lower()]
    for c in candidates:
        for k in npz.files:
            if c.lower() in k.lower():
                return k
    return None


def load_traversal_waveforms(
    npz_path: Path,
) -> Optional[Tuple[np.ndarray, np.ndarray]]:
    """
    Returns
      waves: [latent, level, 12, T] in mV
      levels: [level] in Normal-train SD units

    Handles common layouts produced by script 07.
    """
    if not npz_path.exists():
        warnings.warn(f"Traversal NPZ not found; skipping traversal feature analysis: {npz_path}")
        return None

    npz = np.load(npz_path, allow_pickle=True)
    print("[traversal] NPZ keys:", list(npz.files))

    level_key = _first_key(npz, ["levels", "traversal_levels", "z_levels", "sd_levels"])
    if level_key is not None:
        levels = np.asarray(npz[level_key], dtype=float).ravel()
    else:
        levels = np.asarray([-3, -2, -1, 0, 1, 2, 3], dtype=float)

    # Prefer explicitly mV-named arrays.
    preferred = [
        "waveforms_mv", "generated_mv", "traversals_mv",
        "decoded_mv", "ecg_mv", "median_beats_mv",
    ]
    wave_key = _first_key(npz, preferred)

    if wave_key is None:
        candidates = []
        for k in npz.files:
            a = np.asarray(npz[k])
            if a.ndim in (3, 4) and 12 in a.shape and a.shape[-1] >= 200:
                candidates.append(k)
        if not candidates:
            warnings.warn("Could not identify traversal waveform array in NPZ. Skipping traversal analysis.")
            return None
        wave_key = candidates[0]

    arr = np.asarray(npz[wave_key], dtype=float)
    print(f"[traversal] waveform key='{wave_key}', shape={arr.shape}, levels={levels.tolist()}")

    # Normalize last axes to [12, T].
    if arr.ndim == 4:
        if arr.shape[-2] == 12:
            a = arr
        elif arr.shape[-1] == 12:
            a = np.swapaxes(arr, -1, -2)
        else:
            warnings.warn(f"Traversal 4D array lacks identifiable 12-lead axis: {arr.shape}")
            return None

        # Infer [latent, level, 12, T] vs [level, latent, 12, T].
        if a.shape[1] == len(levels):
            waves = a
        elif a.shape[0] == len(levels):
            waves = np.transpose(a, (1, 0, 2, 3))
        else:
            warnings.warn(
                f"Cannot map traversal dimensions to levels; shape={a.shape}, n_levels={len(levels)}"
            )
            return None

    elif arr.ndim == 3:
        if arr.shape[1] == 12:
            a = arr
        elif arr.shape[2] == 12:
            a = np.transpose(arr, (0, 2, 1))
        else:
            warnings.warn(f"Traversal 3D array lacks identifiable 12-lead axis: {arr.shape}")
            return None

        n_total = a.shape[0]
        if n_total % len(levels) != 0:
            warnings.warn(
                f"Traversal count {n_total} is not divisible by n_levels={len(levels)}."
            )
            return None

        latent_dim = n_total // len(levels)

        # Script 07 was designed as latent-major traversal generation:
        # z0 all levels, z1 all levels, ...
        waves = a.reshape(latent_dim, len(levels), 12, a.shape[-1])

    else:
        warnings.warn(f"Unsupported traversal waveform shape: {arr.shape}")
        return None

    return waves, levels


def quantify_traversals(
    waves: np.ndarray,
    levels: np.ndarray,
    fs: float,
    pre_ms: float,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    rows = []

    latent_dim, n_levels = waves.shape[:2]

    for k in range(latent_dim):
        for j in range(n_levels):
            feat = extract_ecg_features(
                waves[k, j],
                fs=fs,
                pre_ms=pre_ms,
                rr_ms=None,
                lead_names=DEFAULT_LEADS,
            )
            feat["latent"] = f"z_{k:02d}"
            feat["level_sd"] = float(levels[j])
            rows.append(feat)

    feat_df = pd.DataFrame(rows)

    meta_cols = {
        "latent", "level_sd", "feature_extraction_ok", "feature_error",
        "qrs_boundary_method",
    }

    numeric_features = []
    for c in feat_df.columns:
        if c in meta_cols or c.startswith("baseline_mV_"):
            continue
        if c.startswith("T_polarity_"):
            continue
        if c in {"qrs_on_idx", "qrs_off_idx", "qrs_peak_energy_idx", "QRS_axis_deg"}:
            continue
        if pd.api.types.is_numeric_dtype(feat_df[c]):
            if np.isfinite(pd.to_numeric(feat_df[c], errors="coerce")).sum() >= 4:
                numeric_features.append(c)

    slope_rows = []

    for z, zdf in feat_df.groupby("latent"):
        x = pd.to_numeric(zdf["level_sd"], errors="coerce").to_numpy(dtype=float)

        for feat in numeric_features:
            y = pd.to_numeric(zdf[feat], errors="coerce").to_numpy(dtype=float)
            ok = np.isfinite(x) & np.isfinite(y)

            if ok.sum() < 4 or np.std(x[ok]) < EPS or np.std(y[ok]) < EPS:
                continue

            lr = stats.linregress(x[ok], y[ok])

            # Explicit -3 to +3 difference when present; otherwise min to max.
            xmin = np.min(x[ok])
            xmax = np.max(x[ok])
            y_lo = y[np.where(np.isclose(x, xmin) & np.isfinite(y))[0][0]]
            y_hi = y[np.where(np.isclose(x, xmax) & np.isfinite(y))[0][0]]

            slope_rows.append({
                "latent": z,
                "feature": feat,
                "n_levels": int(ok.sum()),
                "level_min_sd": float(xmin),
                "level_max_sd": float(xmax),
                "feature_at_min_sd": float(y_lo),
                "feature_at_max_sd": float(y_hi),
                "delta_min_to_max": float(y_hi - y_lo),
                "slope_per_sd": float(lr.slope),
                "intercept": float(lr.intercept),
                "r_value": float(lr.rvalue),
                "r_squared": float(lr.rvalue ** 2),
                "p_value": float(lr.pvalue),
            })

    slope_df = pd.DataFrame(slope_rows)
    if len(slope_df):
        slope_df["p_q_fdr"] = bh_fdr(slope_df["p_value"].to_numpy())
        slope_df["abs_slope_per_sd"] = np.abs(slope_df["slope_per_sd"])
        slope_df = slope_df.sort_values(
            ["latent", "abs_slope_per_sd"],
            ascending=[True, False],
        ).reset_index(drop=True)

    return feat_df, slope_df


