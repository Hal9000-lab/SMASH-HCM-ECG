def priority_summary(
    assoc_normal: pd.DataFrame,
    assoc_hcm: pd.DataFrame,
    traversal_slopes: pd.DataFrame,
    priority_latents: Sequence[str],
) -> pd.DataFrame:
    """
    Compact table intended for scientific interpretation:
      - strongest real-data physiological associations
      - strongest HCM associations
      - strongest monotonic decoder traversal effects
    """
    rows = []

    for z in priority_latents:
        row: Dict[str, object] = {"latent": z}

        if not assoc_normal.empty and z in set(assoc_normal["latent"]):
            zz = assoc_normal[assoc_normal["latent"] == z].sort_values(
                "abs_spearman_rho", ascending=False
            )
            for rank, (_, r) in enumerate(zz.head(5).iterrows(), start=1):
                row[f"normal_feature_{rank}"] = r["feature"]
                row[f"normal_spearman_{rank}"] = r["spearman_rho"]
                row[f"normal_q_{rank}"] = r["spearman_q_fdr"]

        if not assoc_hcm.empty and z in set(assoc_hcm["latent"]):
            zz = assoc_hcm[assoc_hcm["latent"] == z].sort_values(
                "abs_spearman_rho", ascending=False
            )
            for rank, (_, r) in enumerate(zz.head(5).iterrows(), start=1):
                row[f"hcm_feature_{rank}"] = r["feature"]
                row[f"hcm_spearman_{rank}"] = r["spearman_rho"]
                row[f"hcm_q_{rank}"] = r["spearman_q_fdr"]

        if not traversal_slopes.empty and z in set(traversal_slopes["latent"]):
            # Favor monotonic traversals (high R2) and meaningful absolute change.
            zz = traversal_slopes[traversal_slopes["latent"] == z].copy()
            zz["decoder_score"] = (
                np.abs(zz["delta_min_to_max"]) * np.sqrt(np.clip(zz["r_squared"], 0, 1))
            )
            zz = zz.sort_values("decoder_score", ascending=False)

            for rank, (_, r) in enumerate(zz.head(8).iterrows(), start=1):
                row[f"traversal_feature_{rank}"] = r["feature"]
                row[f"traversal_delta_{rank}"] = r["delta_min_to_max"]
                row[f"traversal_slope_per_sd_{rank}"] = r["slope_per_sd"]
                row[f"traversal_r2_{rank}"] = r["r_squared"]

        rows.append(row)

    return pd.DataFrame(rows)


