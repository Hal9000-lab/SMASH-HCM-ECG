#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
30_review_mimic_near_duplicate_threshold.py

SMASH-HCM -- MIMIC-IV near-duplicate threshold review.

Purpose
-------
Evaluate a prespecified, amplitude-preserving waveform near-identity rule on the
within-subject pair metrics generated by Step 29, before any record collapse.

Primary candidate rule
----------------------
A pair is waveform-near-identical when BOTH of the following hold:

    symmetric NRMSE <= 0.10
    global Pearson r >= 0.995

The maximum lead-specific NRMSE is retained as an audit/QC descriptor only and
is NOT part of the hard near-identity definition. This avoids rejecting globally
near-identical ECGs because of a localized discrepancy in a single lead.

This step does NOT remove or collapse records. It quantifies how many pairs and
subjects satisfy the rule, where those pairs occur in time, and whether pairwise
relations form simple cliques or potentially problematic transitive chains.

A separate "probable duplicate acquisition" audit flag is defined only for
waveform-near-identical pairs acquired within <= 1 hour. This is an audit flag,
not a deletion rule.

Sensitivity
-----------
The same Pearson criterion (r >= 0.995) is reported for global NRMSE cutoffs
0.05, 0.075, 0.10, and 0.125. Max-lead NRMSE is summarized descriptively for
the selected pairs but does not determine selection.

Default input
-------------
Results/29_MIMIC_NearDuplicateCalibration/mimic_within_subject_pair_metrics.csv

Default outputs
---------------
Results/30_MIMIC_NearDuplicateThresholdReview/
    mimic_near_duplicate_primary_pairs.csv
    mimic_near_duplicate_counts_by_timebin.csv
    mimic_near_duplicate_threshold_sensitivity.csv
    mimic_near_duplicate_subject_summary.csv
    mimic_near_duplicate_components.csv
    mimic_near_duplicate_review_report.txt
    mimic_near_duplicate_review.json

Run
---
python Scripts/30_review_mimic_near_duplicate_threshold.py
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict, deque
from pathlib import Path

import numpy as np
import pandas as pd


STEP = 30
STEP_NAME = "MIMIC_NearDuplicateThresholdReview"

PRIMARY_NRMSE = 0.10
PRIMARY_CORR = 0.995
MAX_LEAD_NRMSE_AUDIT_REFERENCE = 0.20
PROBABLE_DUPLICATE_MAX_HOURS = 1.0
SENSITIVITY_NRMSE = [0.05, 0.075, 0.10, 0.125]

TIME_BIN_ORDER = [
    "same_timestamp",
    "gt0_to_5min",
    "gt5min_to_1h",
    "gt1h_to_1d",
    "gt1d_to_7d",
    "gt7d_to_30d",
    "gt30d",
    "unknown_time",
]


def infer_project_root() -> Path:
    candidates = []
    try:
        here = Path(__file__).resolve()
        candidates.extend([here.parent, *here.parents])
    except NameError:
        pass

    cwd = Path.cwd().resolve()
    candidates.extend([cwd, *cwd.parents])

    seen = set()
    for p in candidates:
        if p in seen:
            continue
        seen.add(p)
        if (p / "Data").exists() and (p / "Results").exists():
            return p

    raise RuntimeError(
        "Cannot locate SMASH-HCM project root (expected Data/ and Results/)."
    )


def parse_args():
    root = infer_project_root()

    default_pairs = (
        root
        / "Results"
        / "29_MIMIC_NearDuplicateCalibration"
        / "mimic_within_subject_pair_metrics.csv"
    )
    default_out = root / "Results" / f"{STEP:02d}_{STEP_NAME}"

    ap = argparse.ArgumentParser(
        description="Review a prespecified MIMIC near-identical ECG waveform rule."
    )
    ap.add_argument("--pairs-csv", type=Path, default=default_pairs)
    ap.add_argument("--results-dir", type=Path, default=default_out)
    return ap.parse_args()


def require_columns(df: pd.DataFrame, columns: list[str]) -> None:
    missing = [c for c in columns if c not in df.columns]
    if missing:
        raise KeyError("Step-29 pair table is missing columns: " + ", ".join(missing))


def primary_mask(df: pd.DataFrame, nrmse_threshold: float = PRIMARY_NRMSE) -> pd.Series:
    nrmse = pd.to_numeric(df["symmetric_nrmse"], errors="coerce")
    corr = pd.to_numeric(df["pearson_r"], errors="coerce")
    return (
        nrmse.notna()
        & corr.notna()
        & (nrmse <= float(nrmse_threshold))
        & (corr >= PRIMARY_CORR)
    )


def to_bool_series(s: pd.Series) -> pd.Series:
    """Parse common CSV boolean encodings without treating non-empty strings as True."""
    if pd.api.types.is_bool_dtype(s):
        return s.fillna(False).astype(bool)
    return (
        s.astype(str)
        .str.strip()
        .str.lower()
        .isin(["true", "1", "1.0", "yes", "y"])
    )


def connected_components_for_subject(g: pd.DataFrame) -> list[dict]:
    adjacency: dict[str, set[str]] = defaultdict(set)
    edge_pairs = set()

    for _, r in g.iterrows():
        a = str(r["record_id_1"])
        b = str(r["record_id_2"])
        adjacency[a].add(b)
        adjacency[b].add(a)
        edge_pairs.add(tuple(sorted((a, b))))

    components = []
    visited = set()

    for start in sorted(adjacency):
        if start in visited:
            continue
        q = deque([start])
        visited.add(start)
        nodes = []

        while q:
            u = q.popleft()
            nodes.append(u)
            for v in adjacency[u]:
                if v not in visited:
                    visited.add(v)
                    q.append(v)

        nodes = sorted(nodes)
        k = len(nodes)
        possible_edges = k * (k - 1) // 2
        actual_edges = sum(
            1
            for i in range(k)
            for j in range(i + 1, k)
            if tuple(sorted((nodes[i], nodes[j]))) in edge_pairs
        )
        is_clique = actual_edges == possible_edges

        sub = g[
            g["record_id_1"].astype(str).isin(nodes)
            & g["record_id_2"].astype(str).isin(nodes)
        ].copy()

        ddays = pd.to_numeric(sub["delta_days"], errors="coerce")
        max_pair_days = float(ddays.max()) if ddays.notna().any() else np.nan

        components.append({
            "n_records": k,
            "n_primary_edges": int(actual_edges),
            "n_possible_edges": int(possible_edges),
            "is_complete_clique": bool(is_clique),
            "max_pair_time_days_among_primary_edges": max_pair_days,
            "record_ids": ";".join(nodes),
        })

    return components


def main():
    args = parse_args()
    pairs_csv = args.pairs_csv.resolve()
    out = args.results_dir.resolve()

    if not pairs_csv.exists():
        raise FileNotFoundError(f"Step-29 pair metrics not found:\n{pairs_csv}")

    out.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(pairs_csv)

    require_columns(
        df,
        [
            "subject_id",
            "record_id_1",
            "record_id_2",
            "acquisition_datetime_1",
            "acquisition_datetime_2",
            "delta_days",
            "time_bin",
            "symmetric_nrmse",
            "pearson_r",
            "max_lead_nrmse",
            "exact_waveform_match",
        ],
    )

    df["subject_id"] = df["subject_id"].astype(str)
    df["record_id_1"] = df["record_id_1"].astype(str)
    df["record_id_2"] = df["record_id_2"].astype(str)
    df["delta_days"] = pd.to_numeric(df["delta_days"], errors="coerce")

    df["primary_near_identical"] = primary_mask(df)
    df["probable_duplicate_acquisition"] = (
        df["primary_near_identical"]
        & df["delta_days"].notna()
        & (df["delta_days"] >= 0.0)
        & (df["delta_days"] <= PROBABLE_DUPLICATE_MAX_HOURS / 24.0)
    )

    primary = df[df["primary_near_identical"]].copy()
    primary = primary.sort_values(
        ["subject_id", "delta_days", "record_id_1", "record_id_2"],
        kind="mergesort",
    )
    primary.to_csv(out / "mimic_near_duplicate_primary_pairs.csv", index=False)

    # Counts by acquisition-time bin.
    by_time_rows = []
    for label in TIME_BIN_ORDER:
        g = df[df["time_bin"].astype(str) == label].copy()
        if g.empty:
            continue
        hit = g["primary_near_identical"]
        dup = g["probable_duplicate_acquisition"]
        by_time_rows.append({
            "time_bin": label,
            "n_pairs": int(len(g)),
            "n_primary_near_identical": int(hit.sum()),
            "fraction_primary_near_identical": float(hit.mean()),
            "n_probable_duplicate_acquisition": int(dup.sum()),
            "n_subjects_with_primary_pair": int(g.loc[hit, "subject_id"].nunique()),
            "median_nrmse_primary": (
                float(pd.to_numeric(g.loc[hit, "symmetric_nrmse"], errors="coerce").median())
                if hit.any() else np.nan
            ),
            "median_corr_primary": (
                float(pd.to_numeric(g.loc[hit, "pearson_r"], errors="coerce").median())
                if hit.any() else np.nan
            ),
            "median_max_lead_nrmse_primary": (
                float(pd.to_numeric(g.loc[hit, "max_lead_nrmse"], errors="coerce").median())
                if hit.any() else np.nan
            ),
        })

    by_time = pd.DataFrame(by_time_rows)
    by_time.to_csv(out / "mimic_near_duplicate_counts_by_timebin.csv", index=False)

    # Threshold sensitivity.
    sensitivity_rows = []
    for thr in SENSITIVITY_NRMSE:
        hit = primary_mask(df, nrmse_threshold=thr)
        short = (
            hit
            & df["delta_days"].notna()
            & (df["delta_days"] >= 0.0)
            & (df["delta_days"] <= PROBABLE_DUPLICATE_MAX_HOURS / 24.0)
        )
        sensitivity_rows.append({
            "nrmse_threshold": float(thr),
            "pearson_threshold": PRIMARY_CORR,
            "max_lead_nrmse_threshold": None,
            "max_lead_nrmse_used_for_selection": False,
            "audit_reference_max_lead_nrmse": MAX_LEAD_NRMSE_AUDIT_REFERENCE,
            "n_pairs_max_lead_le_0p20": int(
                (
                    hit
                    & (
                        pd.to_numeric(df["max_lead_nrmse"], errors="coerce")
                        <= MAX_LEAD_NRMSE_AUDIT_REFERENCE
                    )
                ).sum()
            ),
            "n_pairs": int(hit.sum()),
            "n_subjects": int(df.loc[hit, "subject_id"].nunique()),
            "n_pairs_within_1h": int(short.sum()),
            "n_subjects_with_pair_within_1h": int(df.loc[short, "subject_id"].nunique()),
            "fraction_of_all_pairs": float(hit.mean()),
        })

    sensitivity = pd.DataFrame(sensitivity_rows)
    sensitivity.to_csv(out / "mimic_near_duplicate_threshold_sensitivity.csv", index=False)

    # Subject-level summary.
    subject_rows = []
    all_subjects = sorted(set(df["subject_id"].astype(str)))
    for sid in all_subjects:
        g = df[df["subject_id"] == sid]
        gp = g[g["primary_near_identical"]]
        gd = g[g["probable_duplicate_acquisition"]]
        records = set(g["record_id_1"].astype(str)) | set(g["record_id_2"].astype(str))
        involved = set(gp["record_id_1"].astype(str)) | set(gp["record_id_2"].astype(str))
        involved_dup = set(gd["record_id_1"].astype(str)) | set(gd["record_id_2"].astype(str))
        subject_rows.append({
            "subject_id": sid,
            "n_records_represented_in_pair_table": int(len(records)),
            "n_primary_near_identical_pairs": int(len(gp)),
            "n_records_in_primary_pairs": int(len(involved)),
            "n_probable_duplicate_acquisition_pairs": int(len(gd)),
            "n_records_in_probable_duplicate_pairs": int(len(involved_dup)),
        })

    subject_summary = pd.DataFrame(subject_rows)
    subject_summary.to_csv(out / "mimic_near_duplicate_subject_summary.csv", index=False)

    # Connected components from primary pair edges; report clique status so that
    # later deduplication cannot silently rely on transitive chaining.
    component_rows = []
    component_counter = 0
    for sid, g in primary.groupby("subject_id", sort=True):
        comps = connected_components_for_subject(g)
        for c in comps:
            component_counter += 1
            component_rows.append({
                "component_id": component_counter,
                "subject_id": str(sid),
                **c,
            })

    components = pd.DataFrame(component_rows)
    components.to_csv(out / "mimic_near_duplicate_components.csv", index=False)

    n_primary = int(df["primary_near_identical"].sum())
    n_primary_subjects = int(df.loc[df["primary_near_identical"], "subject_id"].nunique())
    n_probdup = int(df["probable_duplicate_acquisition"].sum())
    n_probdup_subjects = int(df.loc[df["probable_duplicate_acquisition"], "subject_id"].nunique())
    n_exact = int(to_bool_series(df["exact_waveform_match"]).sum())

    n_components = int(len(components))
    n_nonclique = (
        int((~components["is_complete_clique"].astype(bool)).sum())
        if not components.empty else 0
    )
    n_components_gt2 = (
        int((pd.to_numeric(components["n_records"], errors="coerce") > 2).sum())
        if not components.empty else 0
    )

    summary = {
        "script": Path(__file__).name,
        "step": STEP,
        "input_pairs_csv": str(pairs_csv),
        "results_dir": str(out),
        "n_total_within_subject_pairs": int(len(df)),
        "n_exact_waveform_matches": n_exact,
        "primary_rule": {
            "symmetric_nrmse_max": PRIMARY_NRMSE,
            "pearson_r_min": PRIMARY_CORR,
            "max_lead_nrmse_used_for_selection": False,
        },
        "max_lead_nrmse_audit_reference": MAX_LEAD_NRMSE_AUDIT_REFERENCE,
        "n_primary_near_identical_pairs": n_primary,
        "n_subjects_with_primary_near_identical_pair": n_primary_subjects,
        "probable_duplicate_audit_rule": {
            "requires_primary_near_identical": True,
            "max_time_hours": PROBABLE_DUPLICATE_MAX_HOURS,
        },
        "n_probable_duplicate_acquisition_pairs": n_probdup,
        "n_subjects_with_probable_duplicate_acquisition_pair": n_probdup_subjects,
        "n_primary_connected_components": n_components,
        "n_components_with_more_than_2_records": n_components_gt2,
        "n_nonclique_components": n_nonclique,
        "interpretation": (
            "Waveform near-identity and probable duplicate acquisition are audit labels only. "
            "No record is removed in Step 30. Non-clique components identify cases where "
            "transitive chaining would be unsafe for later temporal collapse."
        ),
    }

    (out / "mimic_near_duplicate_review.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )

    lines = []
    lines.append("SMASH-HCM Step 30 -- MIMIC near-duplicate threshold review\n")
    lines.append(f"Input pair table: {pairs_csv}\n")
    lines.append(f"Within-subject pairs: {len(df):,}\n")
    lines.append(f"Exact waveform matches: {n_exact:,}\n\n")
    lines.append(
        "Primary waveform near-identity rule: "
        f"NRMSE <= {PRIMARY_NRMSE:.3f} and r >= {PRIMARY_CORR:.3f}.\n"
    )
    lines.append(
        f"Primary near-identical pairs: {n_primary:,} across {n_primary_subjects:,} subjects.\n"
    )
    if n_primary:
        maxlead_primary = pd.to_numeric(
            df.loc[df["primary_near_identical"], "max_lead_nrmse"], errors="coerce"
        )
        lines.append(
            "Max-lead NRMSE is audit-only: "
            f"median={maxlead_primary.median():.3f}, "
            f"range={maxlead_primary.min():.3f}-{maxlead_primary.max():.3f}; "
            f"{int((maxlead_primary <= MAX_LEAD_NRMSE_AUDIT_REFERENCE).sum())}/{n_primary} "
            f"would also satisfy max-lead NRMSE <= {MAX_LEAD_NRMSE_AUDIT_REFERENCE:.2f}.\n"
        )
    lines.append(
        f"Probable duplicate-acquisition audit pairs (primary rule + <=1 h): "
        f"{n_probdup:,} across {n_probdup_subjects:,} subjects.\n\n"
    )

    lines.append("Primary pairs by acquisition-time bin:\n")
    for _, r in by_time.iterrows():
        lines.append(
            f"  {r['time_bin']}: {int(r['n_primary_near_identical'])}/{int(r['n_pairs'])} "
            f"({100.0 * float(r['fraction_primary_near_identical']):.3f}%), "
            f"subjects={int(r['n_subjects_with_primary_pair'])}.\n"
        )

    lines.append("\nNRMSE threshold sensitivity (same Pearson constraint; max-lead audit-only):\n")
    for _, r in sensitivity.iterrows():
        lines.append(
            f"  NRMSE <= {float(r['nrmse_threshold']):.3f}: "
            f"pairs={int(r['n_pairs'])}, subjects={int(r['n_subjects'])}, "
            f"within1h={int(r['n_pairs_within_1h'])}.\n"
        )

    lines.append("\nPrimary-pair graph audit:\n")
    lines.append(f"  connected components: {n_components}\n")
    lines.append(f"  components with >2 records: {n_components_gt2}\n")
    lines.append(f"  non-clique components: {n_nonclique}\n")
    lines.append(
        "\nInterpretation constraint: Step 30 does not deduplicate records. "
        "A later collapse rule should avoid transitive chaining, particularly for non-clique components.\n"
    )

    report = "".join(lines)
    (out / "mimic_near_duplicate_review_report.txt").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
